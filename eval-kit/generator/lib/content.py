def _ratings(n, mean, seed):
    """Integer ratings 1..5 with an exact target sum (n * mean)."""
    rng = np.random.default_rng(seed)
    target = int(round(n * mean))
    r = rng.integers(3, 6, n)
    while r.sum() != target:
        i = rng.integers(n)
        if r.sum() > target and r[i] > 1:
            r[i] -= 1
        elif r.sum() < target and r[i] < 5:
            r[i] += 1
    return r


def responses_csv():
    n = US["participants"]
    seed = NUM["seeds"]["user_study"]
    ease = _ratings(n, US["mean_ease"], seed)
    qual = _ratings(n, US["mean_quality"], seed + 1)
    neutral = ["Easy to follow.", "The sharp wave fronts were convincing.", "Slow to load the first time.",
               "I liked the side-by-side view.", "Labels were too small on my laptop.", "Would use it again.",
               "Not sure what the confidence map means.", "Fine overall.", "Colours were clear.",
               "Took a while to understand the sensor map."]
    insults = {4: "this tool is useless garbage", 11: "whoever designed this is an idiot",
               17: "total waste of my afternoon, absolute junk"}
    b = io.StringIO()
    w = csv.writer(b, lineterminator="\n")
    w.writerow(["participant_id", "name", "email", "phone", "condition", "ease_1to5", "quality_1to5",
                "free_text", "content_warning"])
    for i in range(n):
        pid = f"P{i + 1:02d}"
        flagged = i in insults
        w.writerow([pid, f"Participant Example {i + 1:02d}", f"participant{i + 1:02d}@example.invalid",
                    f"555-01{(i * 7 + 3) % 100:02d}", "A" if i % 2 == 0 else "B", int(ease[i]), int(qual[i]),
                    insults[i] if flagged else neutral[i % len(neutral)], "insult" if flagged else ""])
    assert sum(1 for i in range(n) if i in insults) == US["flagged_free_text"]
    return b.getvalue()


