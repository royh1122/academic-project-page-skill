def md_main_table():
    cols = MT["columns"]
    best = [max(r[1] for r in ROWS), max(r[2] for r in ROWS), min(r[3] for r in ROWS)]
    out = ["| " + " | ".join(cols) + " |", "|---|---:|---:|---:|"]
    for n, p, s, m in ROWS:
        cells = [f"{p:.2f}", f"{s:.3f}", f"{m:.1f}"]
        cells = [f"**{c}**" if v == b else c for c, v, b in zip(cells, (p, s, m), best)]
        out.append(f"| {n} | " + " | ".join(cells) + " |")
    return "\n".join(out)


def md_sweep_table():
    sc = SW["sensor_counts"]
    out = ["| Method | " + " | ".join(f"{c} sensors" for c in sc) + " |",
           "|---|" + "---:|" * len(sc)]
    best = [max(r[i + 1] for r in SW["psnr_rows"]) for i in range(len(sc))]
    for r in SW["psnr_rows"]:
        cells = [f"**{v:.2f}**" if v == best[i] else f"{v:.2f}" for i, v in enumerate(r[1:])]
        out.append(f"| {r[0]} | " + " | ".join(cells) + " |")
    return "\n".join(out)


