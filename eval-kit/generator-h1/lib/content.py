def annotators():
    """Deterministic list of (name, email, country, hours, rate) for the annotators."""
    rng = random.Random(AN["seed"])
    seen, out = set(), []
    while len(out) < AN["count"]:
        n = f"{rng.choice(FIRST)} {rng.choice(LAST)}"
        if n in seen:
            continue
        seen.add(n)
        email = n.lower().replace(" ", ".") + "@" + AN["domain"]
        out.append((n, email, ["Country A", "Country B", "Country C"][len(out) % AN["countries"]],
                    rng.randrange(40, 140), rng.choice([14.5, 15.0, 16.0, 17.5])))
    return out


