def authors_json():
    out = []
    for p in NUM["people"]:
        d = {"name": p["name"]}
        if p.get("native_name"):
            d["native_name"] = p["native_name"]
        d["affiliations"] = [INST[i] for i in p["inst"]]
        if p.get("equal"):
            d["equal_contribution"] = True
        if p["key"] == P["corresponding"]:
            d["corresponding"] = True
            d["email"] = p["email"]
        out.append(d)
    return {"_note": "Author order as in the paper. Equal contribution: the first two authors.", "authors": out}


